SCENARIOS = {
    "promote_twice_then_mastery": ["correct"] * 9,
    "hint_then_correct": ["incorrect", "correct", "correct", "correct"],
    "two_wrong_goes_easier": ["correct", "correct", "incorrect", "incorrect", "correct"],
    "unclear_then_manual": ["unclear", "unclear", "correct"],
    "skip_resets_streak": ["correct", "skipped", "correct", "correct"],
    "recycles_when_exhausted": ["incorrect", "incorrect"] * 6,
}


def build() -> dict:
    scenarios = []
    for name, outcomes in SCENARIOS.items():
        st = engine.start(Q)
        steps = [{"start_question_id": st.current_question_id}]
        for o in outcomes:
            d = engine.apply_outcome(st, Q, o, None)
            steps.append({"outcome": o, "action": d.action, "next_question_id": d.next_question_id,
                          "difficulty": st.difficulty, "attempt": st.attempt, "streak": st.streak,
                          "suggest_manual": d.suggest_manual, "mastery_signal": d.mastery_signal,
                          "show_hint": d.show_hint, "show_explanation": d.show_explanation,
                          "questions_completed": st.questions_completed})
        scenarios.append({"name": name, "steps": steps})
    return {
        "_comment": "Generated by backend/scripts/build_engine_fixtures.py from the reference Python engine.",
        "questions": [q.__dict__ for q in Q],
        "parse": [{"text": t, "value": v, "status": s} for t, v, s in PARSE_CASES],
        "misconceptions": [{"question": q.__dict__, "value": v, "code": c} for q, v, c in MIS_CASES],
        "scenarios": scenarios,
    }


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(build(), ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"wrote {OUT}")
